"""Command-line entry point for implemented project phases."""
import argparse
import importlib
from pathlib import Path


def main(argv=None):
    parser = argparse.ArgumentParser(description="Sign-language project tools")
    commands = parser.add_subparsers(dest="command", required=True)
    p = commands.add_parser("prepare-data", help="Validate and prepare Phase 1 data artifacts")
    p.add_argument("--dataset-root", type=Path, default=Path("phoenix-2014-T.v3/PHOENIX-2014-T-release-v3/PHOENIX-2014-T"))
    p.add_argument("--output", type=Path, default=Path("data/prepared/phase1"))
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--held-out-fraction", type=float, default=0.1)
    p.add_argument("--min-retained", type=float, default=0.2)
    p.add_argument("--held-out-file", type=Path, help="UTF-8 file with one exact training gloss per line")
    p.add_argument("--all-png-headers", action="store_true", help="Check every PNG header, not only the first per clip")
    p.set_defaults(handler=("sign_language.cli.commands.prepare_data", "prepare"))

    p = commands.add_parser("import-corrnet-vocabulary", help="Convert the trusted released gloss dictionary to JSON")
    p.add_argument("--trusted-npy", type=Path, required=True, help="Only use the authors' trusted file: NumPy dictionary loading uses pickle")
    p.add_argument("--output", type=Path, default=Path("artifacts/pretrained/corrnet/vocabulary.json"))
    p.set_defaults(handler=("sign_language.cli.commands.reference_vocabulary", "import_vocabulary"))

    p = commands.add_parser("extract-features", help="Cache frozen CorrNet features and check prediction equivalence")
    p.add_argument("--dataset-root", type=Path, default=Path("phoenix-2014-T.v3/PHOENIX-2014-T-release-v3/PHOENIX-2014-T"))
    p.add_argument("--source", type=Path, default=Path("external/corrnet/upstream"))
    p.add_argument("--checkpoint", type=Path, default=Path("artifacts/pretrained/corrnet/phoenix2014t.pt"))
    p.add_argument("--vocabulary", type=Path, default=Path("artifacts/pretrained/corrnet/vocabulary.json"))
    p.add_argument("--manifest", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--device", default="auto")
    p.add_argument("--limit", type=int)
    p.add_argument("--verify-first", type=int, default=3)
    p.add_argument("--resume", action="store_true")
    p.add_argument("--trust-legacy-checkpoint", action="store_true", help="Allow pickle only for a separately trusted legacy checkpoint")
    p.set_defaults(handler=("sign_language.features.extractor", "extract_features"))

    p = commands.add_parser("train", help="Train the temporal encoder and selected A/B/C or control head")
    p.add_argument("--config", type=Path, default=Path("configs/training/heads.yaml"))
    p.add_argument("--vocabulary", type=Path, default=Path("data/prepared/phase1/vocabularies/reference.json"))
    p.add_argument("--train-cache", type=Path, required=True)
    p.add_argument("--dev-cache", type=Path, required=True)
    p.add_argument("--train-manifest", type=Path)
    p.add_argument("--dev-manifest", type=Path)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--device", default="auto")
    p.add_argument("--resume", action="store_true")
    p.add_argument("--stop-after-epochs", type=int, help="Stop cleanly after this many epochs, retaining the original scheduler budget")
    p.add_argument("--seed", type=int, help="Override the training seed; repeat it when resuming")
    p.add_argument("--allow-synthetic", action="store_true", help="Allow explicitly marked debugging features")
    p.set_defaults(handler=("sign_language.training.trainer", "train_command"))

    p = commands.add_parser("evaluate", help="Score a saved A/B/C or control checkpoint and save predictions")
    p.add_argument("--checkpoint", type=Path, required=True)
    p.add_argument("--cache", type=Path, required=True)
    p.add_argument("--manifest", type=Path)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--batch-size", type=int, default=8)
    p.add_argument("--device", default="auto")
    p.set_defaults(handler=("sign_language.cli.commands.evaluate", "evaluate"))

    p = commands.add_parser("smoke-test", help="Learn four invented sequences to verify the pipeline; no real-data accuracy claim")
    p.add_argument("--output", type=Path, default=Path("runs/phase2_smoke"))
    p.add_argument("--device", default="auto")
    p.add_argument("--max-steps", type=int, default=300)
    p.set_defaults(handler=("sign_language.cli.commands.smoke", "smoke_test"))

    p = commands.add_parser("smoke-test-phase3", help="Check six heads with invented features and text vectors")
    p.add_argument("--output", type=Path, default=Path("runs/phase3_smoke"))
    p.add_argument("--device", default="auto")
    p.add_argument("--max-steps", type=int, default=300)
    p.set_defaults(handler=("sign_language.cli.commands.smoke_phase3", "smoke_phase3"))

    p = commands.add_parser("overfit", help="Learn a few cached training videos as a debugging check")
    p.add_argument("--cache", type=Path, required=True)
    p.add_argument("--vocabulary", type=Path, default=Path("data/prepared/phase1/vocabularies/reference.json"))
    p.add_argument("--config", type=Path, default=Path("configs/training/heads.yaml"))
    p.add_argument("--limit", type=int, default=4)
    p.add_argument("--max-steps", type=int, default=300)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--device", default="auto")
    p.add_argument("--allow-synthetic", action="store_true")
    p.set_defaults(handler=("sign_language.cli.commands.overfit", "overfit"))
    p = commands.add_parser("build-embeddings", help="Build an audited German fastText table in vocabulary order")
    p.add_argument("--vocabulary", type=Path, default=Path("data/prepared/phase1/vocabularies/reference.json"))
    p.add_argument("--fasttext-model", type=Path, required=True)
    p.add_argument("--output", type=Path, default=Path("data/text/embeddings/fasttext/reference"))
    p.add_argument("--strip-prefixes", action="store_true", help="Also strip loc-, cl-, neg-; audit every change")
    p.set_defaults(handler=("sign_language.cli.commands.build_embeddings", "build_embeddings"))

    p = commands.add_parser("compare-runs", help="Summarize comparable dev-selected runs and seed variation")
    p.add_argument("--runs", type=Path, nargs="+", required=True)
    p.add_argument("--output", type=Path, required=True)
    p.set_defaults(handler=("sign_language.evaluation.reporting", "compare_runs"))

    p = commands.add_parser('prepare-unseen-study', help='Freeze reduced train, seen-only dev and unseen candidate IDs')
    p.add_argument('--prepared', type=Path, default=Path('data/prepared/phase1'))
    p.add_argument('--output', type=Path, default=Path('data/prepared/phase4'))
    p.set_defaults(handler=('sign_language.data.unseen_protocol', 'prepare_study'))

    p = commands.add_parser('train-clean-backbone', help='Train fresh CorrNet only on the frozen reduced training clips')
    p.add_argument('--study', type=Path, default=Path('data/prepared/phase4/study.json'))
    p.add_argument('--dataset-root', type=Path, default=Path('phoenix-2014-T.v3/PHOENIX-2014-T-release-v3/PHOENIX-2014-T'))
    p.add_argument('--source', type=Path, default=Path('external/corrnet/upstream'))
    p.add_argument('--imagenet-checkpoint', type=Path, default=Path('artifacts/pretrained/generic/resnet18-f37072fd.pth'))
    p.add_argument('--config', type=Path, default=Path('configs/training/backbone.yaml'))
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--device', default='auto')
    p.add_argument('--resume', action='store_true')
    p.add_argument('--stop-after-epochs', type=int)
    p.set_defaults(handler=('sign_language.training.clean_backbone', 'train_clean'))

    p = commands.add_parser('extract-clean-features', help='Cache features from the reduced-data CorrNet checkpoint')
    p.add_argument('--study', type=Path, default=Path('data/prepared/phase4/study.json'))
    p.add_argument('--dataset-root', type=Path, default=Path('phoenix-2014-T.v3/PHOENIX-2014-T-release-v3/PHOENIX-2014-T'))
    p.add_argument('--source', type=Path, default=Path('external/corrnet/upstream'))
    p.add_argument('--checkpoint', type=Path, required=True)
    p.add_argument('--split', choices=('train', 'dev_seen', 'dev', 'test'), required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--device', default='auto')
    p.add_argument('--resume', action='store_true')
    p.set_defaults(handler=('sign_language.features.clean_extractor', 'extract_clean'))

    p = commands.add_parser('expand-vocabulary', help='Append all held-out text candidates without further training')
    p.add_argument('--study', type=Path, default=Path('data/prepared/phase4/study.json'))
    p.add_argument('--checkpoint', type=Path, required=True)
    p.add_argument('--embeddings', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.set_defaults(handler=('sign_language.inference.vocabulary_expansion', 'expand_vocabulary'))

    p = commands.add_parser('evaluate-unseen', help='Score seen/held-out groups, unseen precision/recall and false guesses')
    p.add_argument('--study', type=Path, default=Path('data/prepared/phase4/study.json'))
    p.add_argument('--checkpoint', type=Path, required=True)
    p.add_argument('--cache', type=Path, required=True)
    p.add_argument('--split', choices=('dev_seen', 'dev', 'test'), required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--device', default='auto')
    p.add_argument('--batch-size', type=int, default=8)
    p.set_defaults(handler=('sign_language.evaluation.unseen', 'evaluate_unseen'))
    p = commands.add_parser('predict', help='Predict glosses for one saved feature-cache clip')
    p.add_argument('--checkpoint', type=Path, required=True)
    p.add_argument('--cache', type=Path, required=True)
    p.add_argument('--clip-id', required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--device', default='auto')
    p.set_defaults(handler=('sign_language.cli.commands.predict', 'predict'))

    p = commands.add_parser('export-model', help='Export model weights, vocabulary and feature provenance')
    p.add_argument('--checkpoint', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.set_defaults(handler=('sign_language.inference.export', 'export_model'))

    p = commands.add_parser('final-report', help='Build result tables and error examples from saved evaluations')
    p.add_argument('--evaluations', type=Path, nargs='+', required=True)
    p.add_argument('--output', type=Path, required=True)
    p.set_defaults(handler=('sign_language.evaluation.final_report', 'final_report'))
    args = parser.parse_args(argv)
    try:
        module, function = args.handler
        getattr(importlib.import_module(module), function)(args)
    except (ValueError, OSError, ImportError, RuntimeError) as error:
        parser.exit(2, f"{args.command} failed: {error}\n")


if __name__ == "__main__":
    main()
